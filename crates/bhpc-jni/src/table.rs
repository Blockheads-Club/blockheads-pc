//! The `JNINativeInterface` function table (JNI 1.6, 233 entries) and `JNIInvokeInterface` (8 entries).

/// How the fake VM answers a JNI function.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    /// Return 0 / NULL / void.
    Zero,
    GetVersion,
    FindClass,
    /// Return the first argument after `env` (reference management).
    Ident,
    /// Return 1 (`IsInstanceOf`, `IsAssignableFrom`).
    One,
    /// `NewObject` family and `AllocObject`: a fresh object of the class.
    NewObject,
    GetObjectClass,
    /// `GetMethodID` / `GetStaticMethodID`.
    MethodId {
        is_static: bool,
    },
    /// `GetFieldID` / `GetStaticFieldID`.
    FieldId {
        is_static: bool,
    },
    /// `Call<Type>Method` in all its forms: recorded, answers 0.
    Call,
    NewString,
    NewStringUtf,
    StringLength,
    StringUtfLength,
    GetStringChars,
    GetStringUtfChars,
    ReleaseStringChars,
    GetArrayLength,
    NewObjectArray,
    GetObjectArrayElement,
    SetObjectArrayElement,
    /// `New<Prim>Array`; the element size in bytes.
    NewPrimArray(u32),
    /// `Get<Prim>ArrayElements`.
    GetArrayElements,
    /// `Release<Prim>ArrayElements`.
    ReleaseArrayElements,
    /// `Get<Prim>ArrayRegion`.
    GetArrayRegion,
    /// `Set<Prim>ArrayRegion`.
    SetArrayRegion,
    RegisterNatives,
    GetJavaVm,
    ExceptionCheck,
    /// `ExceptionOccurred`: a throwable handle while an exception is pending.
    Occurred,
    /// `ExceptionClear`.
    Clear,
    Throw,
    GetObjectRefType,
}

